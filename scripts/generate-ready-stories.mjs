import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { catalog } from '../examples/storybook/catalog.ts'

const target = fileURLToPath(new URL('../examples/storybook/stories/', import.meta.url))
await mkdir(target, { recursive: true })
const expected = new Set()

for (const name of Object.keys(catalog).sort()) {
  const filename = `${name}.stories.ts`
  expected.add(filename)
  // Static CSF titles/exports let Storybook index every preview and give it
  // a stable direct URL. Component data stays in the typed source catalog.
  const title = `Ready/${name}`
  await writeFile(join(target, filename), `// Generated by scripts/generate-ready-stories.mjs.
import { catalog } from '../catalog'
import { nativeStory } from '../host'

export default { title: ${JSON.stringify(title)} }
export const React = nativeStory('${name}', 'React', catalog.${name})
export const Vue = nativeStory('${name}', 'Vue', catalog.${name})
export const Solid = nativeStory('${name}', 'Solid', catalog.${name})
export const Svelte = nativeStory('${name}', 'Svelte', catalog.${name})
`)
}
for (const filename of await readdir(target)) {
  if (/^[A-Za-z]+\.stories\.ts$/.test(filename) && !expected.has(filename)) await rm(join(target, filename))
}
